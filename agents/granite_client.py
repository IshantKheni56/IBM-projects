"""
IBM Granite LLM Client — Nutrition Agentic AI
Handles all interactions with IBM watsonx.ai (IBM Granite model).
"""

import os
import requests
import json
from dotenv import load_dotenv

load_dotenv()

WATSONX_API_KEY = os.getenv("WATSONX_API_KEY", "")
WATSONX_PROJECT_ID = os.getenv("WATSONX_PROJECT_ID", "")
WATSONX_URL = os.getenv("WATSONX_URL", "https://us-south.ml.cloud.ibm.com")

# IBM Granite model identifier
GRANITE_MODEL_ID = "ibm/granite-13b-instruct-v2"

# Token endpoint
IAM_TOKEN_URL = "https://iam.cloud.ibm.com/identity/token"


def get_iam_token() -> str:
    """Exchange IBM API key for an IAM bearer token."""
    headers = {"Content-Type": "application/x-www-form-urlencoded"}
    data = {
        "grant_type": "urn:ibm:params:oauth:grant-type:apikey",
        "apikey": WATSONX_API_KEY
    }
    resp = requests.post(IAM_TOKEN_URL, headers=headers, data=data, timeout=30)
    resp.raise_for_status()
    return resp.json()["access_token"]


def call_granite(prompt: str, max_tokens: int = 1200, temperature: float = 0.4) -> str:
    """
    Call IBM Granite LLM via watsonx.ai REST API.
    Returns the generated text, or a descriptive error string.
    """
    if not WATSONX_API_KEY or WATSONX_API_KEY == "your_ibm_watsonx_api_key_here":
        return _demo_fallback(prompt)

    try:
        token = get_iam_token()
        url = f"{WATSONX_URL}/ml/v1/text/generation?version=2023-05-29"
        headers = {
            "Authorization": f"Bearer {token}",
            "Content-Type": "application/json",
            "Accept": "application/json"
        }
        payload = {
            "model_id": GRANITE_MODEL_ID,
            "input": prompt,
            "parameters": {
                "decoding_method": "greedy",
                "max_new_tokens": max_tokens,
                "temperature": temperature,
                "repetition_penalty": 1.1,
                "stop_sequences": ["Human:", "User:"]
            },
            "project_id": WATSONX_PROJECT_ID
        }
        resp = requests.post(url, headers=headers, json=payload, timeout=60)
        resp.raise_for_status()
        result = resp.json()
        return result["results"][0]["generated_text"].strip()
    except requests.exceptions.HTTPError as e:
        return f"[API Error] {str(e)} — Please verify your WATSONX_API_KEY and WATSONX_PROJECT_ID in the .env file."
    except Exception as e:
        return f"[Connection Error] {str(e)} — Please check your internet connection and credentials."


def _demo_fallback(prompt: str) -> str:
    """
    Demo mode: returns a rich pre-built nutrition plan when no API key is set.
    This allows the app to be demonstrated without credentials.
    """
    if "nutrition plan" in prompt.lower() or "meal plan" in prompt.lower():
        return _build_demo_nutrition_plan(prompt)
    elif "query" in prompt.lower() or "question" in prompt.lower():
        return _build_demo_query_response(prompt)
    return (
        "**Demo Mode Active** — IBM Granite LLM is not connected. "
        "Please add your WATSONX_API_KEY and WATSONX_PROJECT_ID to the `.env` file to activate the live model. "
        "A sample response is shown below for demonstration purposes."
    )


