"""
Guardrails Module — Nutrition Agentic AI
Implements ethical AI safeguards, input validation, and harm prevention.
Following HAM (Helpful, Accurate, Mindful) principles.
"""

import re

# ─── Harmful / Restricted Topic Patterns ────────────────────────────────────
HARMFUL_PATTERNS = [
    r"\b(poison|toxic|overdose|starve|starvation|purge|binge)\b",
    r"\b(diet pill|laxative abuse|diuretic abuse)\b",
    r"\b(suicide|self.harm|hurt myself)\b",
    r"\b(extreme fast|water fast for \d+ days)\b",
    r"\b(500 calorie|300 calorie|200 calorie)\b",  # dangerously low intakes
]

# ─── Medical Red Flags requiring professional referral ───────────────────────
MEDICAL_REFERRAL_CONDITIONS = {
    "cancer", "chemotherapy", "kidney failure", "renal failure",
    "liver failure", "eating disorder", "anorexia", "bulimia",
    "crohn", "celiac", "phenylketonuria", "pku",
    "end stage", "dialysis", "transplant"
}

# ─── Allowed Medical Conditions (handled with care) ─────────────────────────
SUPPORTED_CONDITIONS = {
    "diabetes", "type 2 diabetes", "type 1 diabetes", "prediabetes",
    "hypertension", "high blood pressure", "blood pressure",
    "high cholesterol", "cholesterol", "obesity", "overweight",
    "thyroid", "hypothyroidism", "hyperthyroidism",
    "pcos", "polycystic ovary syndrome",
    "heart disease", "cardiovascular",
    "gout", "arthritis", "ibs", "irritable bowel",
    "acid reflux", "gerd", "lactose intolerance",
    "none", "healthy", "no conditions", "n/a", ""
}

MEDICAL_DISCLAIMER = """
---

## ⚕️ Medical Disclaimer

> **IMPORTANT**: This nutrition plan is generated by an AI system (IBM Granite LLM) for **informational and educational purposes only**. It does **NOT** constitute medical advice, diagnosis, or treatment.

**Please note:**
- Always consult a **registered dietitian (RD)**, **nutritionist**, or **licensed physician** before making significant dietary changes.
- If you have a medical condition (diabetes, hypertension, heart disease, etc.), your healthcare provider should review and approve any nutrition plan.
- Individual nutritional needs vary based on genetics, metabolism, medications, and other factors not captured in this assessment.
- This AI cannot replace personalised professional medical guidance.
- In case of a **medical emergency**, contact your local emergency services immediately.

*Generated by Nutrition Agentic AI — Powered by IBM Granite LLM*
"""


def check_harmful_content(text: str) -> dict:
    """
    Scans input text for harmful patterns.
    Returns: { "safe": bool, "reason": str }
    """
    text_lower = text.lower()
    for pattern in HARMFUL_PATTERNS:
        if re.search(pattern, text_lower, re.IGNORECASE):
            return {
                "safe": False,
                "reason": (
                    "Your query contains content that could promote harmful behaviour. "
                    "For your safety, I cannot provide advice on this topic. "
                    "Please consult a healthcare professional if you need support."
                )
            }
    return {"safe": True, "reason": ""}


def check_medical_referral(medical_history: str) -> dict:
    """
    Checks if the user's condition requires mandatory professional referral.
    Returns: { "requires_referral": bool, "conditions": list }
    """
    history_lower = medical_history.lower()
    flagged = [c for c in MEDICAL_REFERRAL_CONDITIONS if c in history_lower]
    if flagged:
        return {
            "requires_referral": True,
            "conditions": flagged,
            "message": (
                f"Your medical history mentions **{', '.join(flagged)}**. "
                "Nutrition for these conditions requires specialised medical supervision. "
                "I strongly recommend consulting a registered dietitian or your treating physician "
                "before following any nutrition plan. I can still provide general healthy eating "
                "guidelines, but please treat them as supplementary information only."
            )
        }
    return {"requires_referral": False, "conditions": [], "message": ""}


def validate_user_profile(profile: dict) -> dict:
    """
    Validates the user profile for completeness and safety.
    Returns: { "valid": bool, "errors": list }
    """
    errors = []

    # Name validation
    name = profile.get("name", "").strip()
    if not name or len(name) < 2:
        errors.append("Please provide a valid name (at least 2 characters).")

    # Age validation
    try:
        age = int(profile.get("age", 0))
        if age < 5 or age > 120:
            errors.append("Age must be between 5 and 120 years.")
    except (ValueError, TypeError):
        errors.append("Please enter a valid age (numeric value).")

    # Diet preference validation
    diet = profile.get("diet_preference", "").lower()
    if diet not in ["vegetarian", "vegan", "non-vegetarian", "non-veg", "veg", "pescatarian", "flexitarian"]:
        errors.append("Diet preference must be one of: Vegetarian, Vegan, Non-Vegetarian, Pescatarian, or Flexitarian.")

    # Location validation
    city = profile.get("city", "").strip()
    country = profile.get("country", "").strip()
    if not city or len(city) < 2:
        errors.append("Please provide a valid city name.")
    if not country or len(country) < 2:
        errors.append("Please provide a valid country name.")

    # Check harmful content in free-text fields
    free_text_fields = [
        profile.get("medical_history", ""),
        profile.get("goals", ""),
        profile.get("allergies", ""),
    ]
    for field_text in free_text_fields:
        harm_check = check_harmful_content(field_text)
        if not harm_check["safe"]:
            errors.append(harm_check["reason"])
            break

    return {
        "valid": len(errors) == 0,
        "errors": errors
    }


def sanitize_input(text: str) -> str:
    """Sanitize user input — strip HTML tags and limit length."""
    # Remove HTML tags
    text = re.sub(r'<[^>]+>', '', text)
    # Remove script injections
    text = re.sub(r'(?i)(javascript|vbscript|onload|onerror):', '', text)
    # Limit length
    return text[:500].strip()


def get_medical_disclaimer() -> str:
    """Return the standard medical disclaimer."""
    return MEDICAL_DISCLAIMER
